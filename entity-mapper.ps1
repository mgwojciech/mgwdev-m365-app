#region Dataverse metadata

function Invoke-Dataverse([string]$RelativeUrl) {
    $headers = @{
        Authorization      = "Bearer $script:AccessToken"
        Accept             = 'application/json'
        'OData-MaxVersion' = '4.0'
        'OData-Version'    = '4.0'
    }
    try {
        return Invoke-RestMethod -Method Get -Uri "$DataverseUrl/api/data/v9.2/$RelativeUrl" -Headers $headers
    }
    catch {
        $raw = Get-ErrorBody $_
        if ($raw) { throw "Dataverse request failed ($RelativeUrl): $raw" }
        throw
    }
}

function Get-Label($Label, [string]$Fallback) {
    if ($Label) {
        if ($Label.UserLocalizedLabel -and $Label.UserLocalizedLabel.Label) { return $Label.UserLocalizedLabel.Label }
        if ($Label.LocalizedLabels -and $Label.LocalizedLabels.Count -gt 0) { return $Label.LocalizedLabels[0].Label }
    }
    return $Fallback
}

function Get-EntityList {
    $select = 'LogicalName,SchemaName,DisplayName,EntitySetName,IsCustomEntity,IsPrivate,PrimaryIdAttribute,PrimaryNameAttribute'
    $result = Invoke-Dataverse "EntityDefinitions?`$select=$select"
    return $result.value |
        Where-Object { -not $_.IsPrivate -and $_.EntitySetName } |
        ForEach-Object {
            [pscustomobject]@{
                LogicalName          = $_.LogicalName
                DisplayName          = Get-Label $_.DisplayName $_.SchemaName
                SchemaName           = $_.SchemaName
                EntitySetName        = $_.EntitySetName
                IsCustom             = [bool]$_.IsCustomEntity
                PrimaryIdAttribute   = $_.PrimaryIdAttribute
                PrimaryNameAttribute = $_.PrimaryNameAttribute
            }
        } |
        Sort-Object @{ Expression = { -not $_.IsCustom } }, DisplayName
}

function Get-EntityAttributes([string]$LogicalName) {
    $select = 'LogicalName,SchemaName,AttributeType,AttributeTypeName,AttributeOf,IsValidForRead,IsCustomAttribute,DisplayName'
    return (Invoke-Dataverse "EntityDefinitions(LogicalName='$LogicalName')/Attributes?`$select=$select").value
}

# Returns hashtable: attribute logical name -> array of @{ Value; Label }
function Get-EntityOptionSets([string]$LogicalName) {
    $optionSets = @{}
    $queries = @(
        'Microsoft.Dynamics.CRM.PicklistAttributeMetadata?$select=LogicalName&$expand=OptionSet($select=Options),GlobalOptionSet($select=Options)',
        'Microsoft.Dynamics.CRM.MultiSelectPicklistAttributeMetadata?$select=LogicalName&$expand=OptionSet($select=Options),GlobalOptionSet($select=Options)',
        'Microsoft.Dynamics.CRM.StateAttributeMetadata?$select=LogicalName&$expand=OptionSet($select=Options)',
        'Microsoft.Dynamics.CRM.StatusAttributeMetadata?$select=LogicalName&$expand=OptionSet($select=Options)'
    )
    foreach ($query in $queries) {
        foreach ($attribute in (Invoke-Dataverse "EntityDefinitions(LogicalName='$LogicalName')/Attributes/$query").value) {
            $set = $attribute.OptionSet
            if ((-not $set -or -not $set.Options) -and $attribute.GlobalOptionSet) { $set = $attribute.GlobalOptionSet }
            if (-not $set -or -not $set.Options) { continue }
            $optionSets[$attribute.LogicalName] = @($set.Options | ForEach-Object {
                    @{ Value = [int]$_.Value; Label = Get-Label $_.Label "Value$($_.Value)" }
                })
        }
    }
    return $optionSets
}

function Get-EntityRelationships([string]$LogicalName) {
    $expand = @(
        'ManyToOneRelationships($select=SchemaName,ReferencedEntity,ReferencingAttribute,ReferencingEntityNavigationPropertyName)',
        'OneToManyRelationships($select=SchemaName,ReferencingEntity,ReferencingAttribute,ReferencedEntityNavigationPropertyName)',
        'ManyToManyRelationships($select=SchemaName,Entity1LogicalName,Entity2LogicalName,Entity1NavigationPropertyName,Entity2NavigationPropertyName)'
    ) -join ','
    return Invoke-Dataverse "EntityDefinitions(LogicalName='$LogicalName')?`$select=LogicalName&`$expand=$expand"
}

