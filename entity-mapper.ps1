function ConvertFrom-SelectionInput([string]$Text, [int]$Max) {
    $indexes = New-Object System.Collections.Generic.List[int]
    foreach ($part in ($Text -split '[,;\s]+' | Where-Object { $_ })) {
        if ($part -match '^(\d+)-(\d+)$') {
            [int]$Matches[1]..[int]$Matches[2] | ForEach-Object { $indexes.Add($_) }
        }
        elseif ($part -match '^\d+$') {
            $indexes.Add([int]$part)
        }
        else {
            Write-Warning "Ignoring '$part'."
        }
    }
    return $indexes | Where-Object { $_ -ge 1 -and $_ -le $Max } | Select-Object -Unique
}

function Select-TablesConsole($Entities) {
    while ($true) {
        $filter = Read-Host 'Filter tables by name (empty = custom tables only, * = all)'
        $candidates = @(switch ($filter) {
                '' { $Entities | Where-Object IsCustom }
                '*' { $Entities }
                default { $Entities | Where-Object { $_.LogicalName -like "*$filter*" -or $_.DisplayName -like "*$filter*" } }
            })
        if ($candidates.Count -eq 0) {
            Write-Host 'No tables match.' -ForegroundColor Yellow
            continue
        }
        for ($i = 0; $i -lt $candidates.Count; $i++) {
            Write-Host ('{0,4}. {1,-45} {2}' -f ($i + 1), $candidates[$i].LogicalName, $candidates[$i].DisplayName)
        }
        $answer = Read-Host 'Select tables (e.g. 1,3,5-7; empty = filter again)'
        $picked = @(ConvertFrom-SelectionInput $answer $candidates.Count | ForEach-Object { $candidates[$_ - 1] })
        if ($picked.Count -gt 0) { return $picked }
    }
}

function Select-Tables($Entities) {
    if (-not $NoGui -and (Get-Command Out-GridView -ErrorAction SilentlyContinue)) {
        Write-Host 'Select tables in the grid window (Ctrl/Shift for multi-select), then click OK.' -ForegroundColor Cyan
        $picked = @($Entities |
                Select-Object DisplayName, LogicalName, IsCustom, EntitySetName |
                Out-GridView -Title 'Select Dataverse tables to map' -OutputMode Multiple)
        return @($picked | ForEach-Object { $name = $_.LogicalName; $Entities | Where-Object LogicalName -eq $name })
    }
    return Select-TablesConsole $Entities
}

function Resolve-OutputPath([string]$Path) {
    if (-not $Path) { $Path = 'src/model' }
    if ($Path -match '^[A-Za-z]:[\\/]' -or $Path -match '^\\\\') { return $Path }
    return Join-Path $ScriptRoot ($Path.TrimStart('/', '\'))
}

