        })
}
else {
    $selected = @(Select-Tables $entities)
}
if ($selected.Count -eq 0) {
    Write-Host 'No tables selected.' -ForegroundColor Yellow
    return
}
Write-Host "Selected: $(($selected | ForEach-Object LogicalName) -join ', ')"

if (-not $OutputPath) {
    $OutputPath = Read-Host 'Model location [src/model]'
}
$outputDir = Resolve-OutputPath $OutputPath
if (-not (Test-Path $outputDir)) { New-Item -ItemType Directory -Path $outputDir | Out-Null }
Write-Host "Output: $outputDir"

$selectedNames = @($selected | ForEach-Object LogicalName)
# A related table gets a typed navigation property when it is generated now or was generated earlier into the same folder.
$resolveTargetType = {
    param([string]$LogicalName)
    $name = $typeNames[$LogicalName]
    if (-not $name) { return $null }
    if ($selectedNames -contains $LogicalName) { return $name }
    $file = Join-Path $outputDir "$name.ts"
    if ((Test-Path $file) -and (Select-String -Path $file -SimpleMatch "// @entity $LogicalName" -Quiet)) { return $name }
    return $null
}.GetNewClosure()

$utf8NoBom = New-Object Text.UTF8Encoding $false
$overwriteAll = [bool]$Force
foreach ($entity in $selected) {
    $typeName = $typeNames[$entity.LogicalName]
    $file = Join-Path $outputDir "$typeName.ts"
    Write-Host "Mapping $($entity.LogicalName) -> $typeName.ts" -ForegroundColor Cyan

    if ((Test-Path $file) -and -not $overwriteAll) {
        $answer = Read-Host "  $typeName.ts exists. Overwrite? [y]es / [n]o / [a]ll"
        if ($answer -match '^a') { $overwriteAll = $true }
        elseif ($answer -notmatch '^y') { Write-Host '  Skipped.'; continue }
    }

    $attributes = Get-EntityAttributes $entity.LogicalName
    $optionSets = Get-EntityOptionSets $entity.LogicalName
    $relationships = Get-EntityRelationships $entity.LogicalName

    $model = New-EntityModel $entity $typeName $attributes $optionSets $relationships $resolveTargetType
    [IO.File]::WriteAllText($file, $model.Content, $utf8NoBom)

    if ($model.SkippedNavigation -gt 0) {
        Write-Host "  Skipped $($model.SkippedNavigation) navigation properties to unmapped tables (use -IncludeAllRelationships to keep them)." -ForegroundColor DarkGray
    }
}

Write-Host 'Done.' -ForegroundColor Green

