#region Authentication

function ConvertTo-Base64Url([byte[]]$Bytes) {
    return [Convert]::ToBase64String($Bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function Get-RandomBytes([int]$Count) {
    $bytes = New-Object byte[] $Count
    $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($bytes)
    $rng.Dispose()
    return , $bytes
}

function Get-ErrorBody($ErrorRecord) {
    if ($ErrorRecord.ErrorDetails -and $ErrorRecord.ErrorDetails.Message) { return $ErrorRecord.ErrorDetails.Message }
    $response = $ErrorRecord.Exception.Response
    if ($response) {
        $reader = New-Object IO.StreamReader($response.GetResponseStream())
        return $reader.ReadToEnd()
    }
    return $null
}

# Returns the token endpoint response; OAuth errors are returned as objects with an 'error' property.
function Invoke-TokenEndpoint([hashtable]$Body) {
    try {
        return Invoke-RestMethod -Method Post -Uri "$Authority/token" -Body $Body -ContentType 'application/x-www-form-urlencoded'
    }
    catch {
        $raw = Get-ErrorBody $_
        if ($raw) {
            try { return $raw | ConvertFrom-Json } catch { }
        }
        throw
    }
}

function Assert-Token($Response) {
    if ($Response.error) {
        $hint = ''
        if ($Response.error_description -match 'AADSTS9002327') {
            $hint = "`nClient $ClientId is a SPA registration. Pass a public client via -ClientId."
        }
        elseif ($Response.error_description -match 'AADSTS7000218') {
            $hint = "`nClient $ClientId does not allow public client flows. Use -AuthFlow Interactive."
        }
        elseif ($Response.error_description -match 'AADSTS53003') {
            $hint = "`nBlocked by Conditional Access in tenant $TenantId. Try the other -AuthFlow or ask your admin to allow client $ClientId."
        }
        throw "Authentication failed: $($Response.error) - $($Response.error_description)$hint"
    }
    return $Response.access_token
}

function Get-FreePort {
    $tcp = New-Object Net.Sockets.TcpListener([Net.IPAddress]::Loopback, 0)
    $tcp.Start()
    $port = $tcp.LocalEndpoint.Port
    $tcp.Stop()
    return $port
}

function Get-TokenInteractive {
    $verifier = ConvertTo-Base64Url (Get-RandomBytes 32)
    $sha = [Security.Cryptography.SHA256]::Create()
    $challenge = ConvertTo-Base64Url $sha.ComputeHash([Text.Encoding]::ASCII.GetBytes($verifier))
    $sha.Dispose()
    $state = ConvertTo-Base64Url (Get-RandomBytes 16)

    $port = Get-FreePort
    $redirectUri = "http://localhost:$port"
    $listener = New-Object Net.HttpListener
    $listener.Prefixes.Add("$redirectUri/")
    $listener.Start()

    try {
        $query = @(
            "client_id=$ClientId",
            'response_type=code',
            'response_mode=query',
            "redirect_uri=$([Uri]::EscapeDataString($redirectUri))",
            "scope=$([Uri]::EscapeDataString($Scope))",
            "state=$state",
            "code_challenge=$challenge",
            'code_challenge_method=S256',
            'prompt=select_account'
        ) -join '&'
        Write-Host 'Opening browser for sign-in...' -ForegroundColor Cyan
        Start-Process "$Authority/authorize?$query"

        $deadline = (Get-Date).AddMinutes(5)
        $params = $null
        while (-not $params) {
            $pending = $listener.BeginGetContext($null, $null)
            while (-not $pending.AsyncWaitHandle.WaitOne(500)) {
                if ((Get-Date) -gt $deadline) { throw 'Timed out waiting for sign-in.' }
            }
            $context = $listener.EndGetContext($pending)
            $request = $context.Request.QueryString

            $html = '<html><body style="font-family:sans-serif"><h3>Sign-in complete. You can close this window.</h3></body></html>'
            if ($request['error']) { $html = "<html><body style=""font-family:sans-serif""><h3>Sign-in failed: $($request['error'])</h3></body></html>" }
            $buffer = [Text.Encoding]::UTF8.GetBytes($html)
            $context.Response.ContentType = 'text/html; charset=utf-8'
            $context.Response.OutputStream.Write($buffer, 0, $buffer.Length)
            $context.Response.Close()

            if ($request['code'] -or $request['error']) { $params = $request }
        }
    }
    finally {
        $listener.Stop()
        $listener.Close()
    }

    if ($params['error']) { throw "Sign-in failed: $($params['error']) - $($params['error_description'])" }
    if ($params['state'] -ne $state) { throw 'Sign-in failed: state mismatch.' }

    return Assert-Token (Invoke-TokenEndpoint @{
            client_id     = $ClientId
            grant_type    = 'authorization_code'
            code          = $params['code']
            redirect_uri  = $redirectUri
            code_verifier = $verifier
            scope         = $Scope
        })
}

function Get-TokenDeviceCode {
    $device = Invoke-RestMethod -Method Post -Uri "$Authority/devicecode" -ContentType 'application/x-www-form-urlencoded' -Body @{
        client_id = $ClientId
        scope     = $Scope
    }
    Write-Host $device.message -ForegroundColor Cyan

    $interval = [int]$device.interval
    $deadline = (Get-Date).AddSeconds([int]$device.expires_in)
    while ((Get-Date) -lt $deadline) {
        Start-Sleep -Seconds $interval
        $response = Invoke-TokenEndpoint @{
            client_id   = $ClientId
            grant_type  = 'urn:ietf:params:oauth:grant-type:device_code'
            device_code = $device.device_code
        }
        switch ($response.error) {
            'authorization_pending' { continue }
            'slow_down' { $interval += 5; continue }
            default { return Assert-Token $response }
        }
    }
    throw 'Device code expired before sign-in completed.'
}

