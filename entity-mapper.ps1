#region TypeScript generation

function ConvertTo-PascalCase([string]$Text) {
    $words = $Text -split '[^A-Za-z0-9]+' | Where-Object { $_ }
    return ($words | ForEach-Object { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) }) -join ''
}

function ConvertTo-Identifier([string]$Text, [string]$Fallback) {
    $name = ConvertTo-PascalCase $Text
    if (-not $name) { return $Fallback }
    if ($name -match '^\d') { return "_$name" }
    return $name
}

function Format-Comment([string]$Text) {
    return $Text.Replace('*/', '* /') -replace '\s+', ' '
}

# Builds logical name -> TypeScript type name, using the display name and falling back to the schema name on clashes.
function Get-TypeNameMap($Entities) {
    $candidates = @{}
    foreach ($entity in $Entities) {
        $candidates[$entity.LogicalName] = ConvertTo-Identifier $entity.DisplayName (ConvertTo-PascalCase $entity.SchemaName)
    }
    $clashes = $candidates.Values | Group-Object | Where-Object Count -gt 1 | ForEach-Object Name
    $map = @{}
    foreach ($entity in $Entities) {
        $name = $candidates[$entity.LogicalName]
        if ($clashes -contains $name) { $name = ConvertTo-Identifier $entity.SchemaName $name }
        $map[$entity.LogicalName] = $name
    }
    return $map
}

function Get-OptionSetTypeName([string]$TypeName, $Attribute) {
    $schema = $Attribute.SchemaName
    if ($Attribute.IsCustomAttribute -and $schema -match '^[^_]+_(.+)$') { $schema = $Matches[1] }
    return $TypeName + (ConvertTo-PascalCase $schema)
}

function Get-NavigationProperties($Relationships, [string]$LogicalName) {
    $properties = [ordered]@{}
    foreach ($r in $Relationships.ManyToOneRelationships) {
        $name = $r.ReferencingEntityNavigationPropertyName
        if ($name -and -not $properties.Contains($name)) {
            $properties[$name] = @{ Target = $r.ReferencedEntity; Collection = $false; Comment = "N:1 $($r.SchemaName) (_$($r.ReferencingAttribute)_value)" }
        }
    }
    foreach ($r in $Relationships.OneToManyRelationships) {
        $name = $r.ReferencedEntityNavigationPropertyName
        if ($name -and -not $properties.Contains($name)) {
            $properties[$name] = @{ Target = $r.ReferencingEntity; Collection = $true; Comment = "1:N $($r.SchemaName) ($($r.ReferencingEntity).$($r.ReferencingAttribute))" }
        }
    }
    foreach ($r in $Relationships.ManyToManyRelationships) {
        $sides = @()
        if ($r.Entity1LogicalName -eq $LogicalName) { $sides += , @($r.Entity1NavigationPropertyName, $r.Entity2LogicalName) }
        if ($r.Entity2LogicalName -eq $LogicalName) { $sides += , @($r.Entity2NavigationPropertyName, $r.Entity1LogicalName) }
        foreach ($side in $sides) {
            $name = $side[0]
            if ($name -and -not $properties.Contains($name)) {
                $properties[$name] = @{ Target = $side[1]; Collection = $true; Comment = "N:N $($r.SchemaName)" }
            }
        }
    }
    return $properties
}

function New-EntityModel($Entity, [string]$TypeName, $Attributes, [hashtable]$OptionSets, $Relationships, [scriptblock]$ResolveTargetType) {
    $optionBlocks = New-Object System.Collections.Generic.List[string]
    $properties = New-Object System.Collections.Generic.List[string]
    $imports = New-Object System.Collections.Generic.SortedSet[string]

    $lookupTargets = @{}
    foreach ($r in $Relationships.ManyToOneRelationships) {
        if (-not $lookupTargets.ContainsKey($r.ReferencingAttribute)) { $lookupTargets[$r.ReferencingAttribute] = @() }
        $lookupTargets[$r.ReferencingAttribute] += $r.ReferencedEntity
    }

    foreach ($attribute in ($Attributes | Sort-Object LogicalName)) {
        if ($attribute.AttributeOf -or $attribute.IsValidForRead -eq $false) { continue }

        $name = $attribute.LogicalName
        $comment = Get-Label $attribute.DisplayName $null
        $attributeTypeName = $attribute.AttributeTypeName.Value
        $tsType = $null

        switch ($attribute.AttributeType) {
            { $_ -in 'String', 'Memo', 'EntityName', 'Uniqueidentifier', 'DateTime' } { $tsType = 'string' }
            { $_ -in 'Integer', 'BigInt', 'Decimal', 'Double', 'Money' } { $tsType = 'number' }
            'Boolean' { $tsType = 'boolean' }
            'ManagedProperty' { $tsType = '{ Value: boolean; CanBeChanged: boolean; ManagedPropertyLogicalName: string }' }
            { $_ -in 'Lookup', 'Customer', 'Owner' } {
                $name = "_$($attribute.LogicalName)_value"
                $tsType = 'string'
                if ($lookupTargets.ContainsKey($attribute.LogicalName)) {
                    $comment = "$comment -> $(($lookupTargets[$attribute.LogicalName] | Select-Object -Unique) -join ', ')"
                }
            }
            { $_ -in 'Picklist', 'State', 'Status', 'Virtual' } {
                if ($_ -eq 'Virtual' -and $attributeTypeName -notin 'MultiSelectPicklistType', 'ImageType') { break }
                if ($attributeTypeName -eq 'ImageType') { $tsType = 'string'; break }

                $options = $OptionSets[$attribute.LogicalName]
                $isMultiSelect = $attributeTypeName -eq 'MultiSelectPicklistType'
                if ($options) {
                    $optionType = Get-OptionSetTypeName $TypeName $attribute
                    $usedKeys = @{}
                    $members = foreach ($option in ($options | Sort-Object { $_.Value })) {
                        $key = ConvertTo-Identifier $option.Label "Value$($option.Value)"
                        if ($usedKeys.ContainsKey($key)) { $key = "${key}_$($option.Value)" }
                        $usedKeys[$key] = $true
                        "    $key`: $($option.Value),"
                    }
                    $optionBlocks.Add((@(
                                "export const $optionType = {"
                                $members
                                '} as const;'
                                ''
                                "export type $optionType = (typeof $optionType)[keyof typeof $optionType];"
                            ) -join "`n"))
                    if ($isMultiSelect) {
                        $tsType = 'string'
                        $comment = "$comment (comma separated $optionType values)"
                    }
                    else {
                        $tsType = $optionType
                    }
                }
                elseif ($isMultiSelect) { $tsType = 'string' }
                else { $tsType = 'number' }
            }
        }

        if (-not $tsType) { continue }
        if ($comment) { $properties.Add("    /** $(Format-Comment $comment) */") }
        $properties.Add("    $name`?: $tsType | null;")
    }

    $navigation = Get-NavigationProperties $Relationships $Entity.LogicalName
    $navigationLines = New-Object System.Collections.Generic.List[string]
    $skipped = 0
    foreach ($name in ($navigation.Keys | Sort-Object)) {
        $nav = $navigation[$name]
        $targetType = & $ResolveTargetType $nav.Target
        if (-not $targetType) {
            if (-not $IncludeAllRelationships) { $skipped++; continue }
            $targetType = 'Record<string, unknown>'
        }
        elseif ($targetType -ne $TypeName) {
            [void]$imports.Add($targetType)
        }
        $navigationLines.Add("    /** $(Format-Comment $nav.Comment) */")
        if ($nav.Collection) { $navigationLines.Add("    $name`?: $targetType[];") }
        else { $navigationLines.Add("    $name`?: $targetType | null;") }
    }

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("// $GeneratedMarker from $DataverseUrl - do not edit manually.")
    $lines.Add("// @entity $($Entity.LogicalName)")
    $lines.Add('')
    if ($imports.Count -gt 0) {
        foreach ($import in $imports) { $lines.Add("import type { $import } from `"./$import`";") }
        $lines.Add('')
    }
    $lines.Add("export const ${TypeName}Metadata = {")
    $lines.Add("    logicalName: `"$($Entity.LogicalName)`",")
    $lines.Add("    entitySetName: `"$($Entity.EntitySetName)`",")
    $lines.Add("    primaryIdAttribute: `"$($Entity.PrimaryIdAttribute)`",")
    if ($Entity.PrimaryNameAttribute) { $lines.Add("    primaryNameAttribute: `"$($Entity.PrimaryNameAttribute)`",") }
    $lines.Add('} as const;')
    $lines.Add('')
    foreach ($block in $optionBlocks) {
        $lines.Add($block)
        $lines.Add('')
    }
    $lines.Add("/** $(Format-Comment $Entity.DisplayName) ($($Entity.LogicalName)) */")
    $lines.Add("export type $TypeName = {")
    $lines.AddRange($properties)
    if ($navigationLines.Count -gt 0) {
        $lines.Add('')
        $lines.Add('    // Navigation properties')
        $lines.AddRange($navigationLines)
    }
    $lines.Add('};')

    return @{ Content = ($lines -join "`n") + "`n"; SkippedNavigation = $skipped }
}

