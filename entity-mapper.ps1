$TenantId = Get-Setting $envValues 'VITE_FRONTEND_TENANT_ID'
$DataverseUrl = (Get-Setting $envValues 'VITE_FRONTEND_DATAVERSE_ENV').TrimEnd('/')

$Authority = "https://login.microsoftonline.com/$TenantId/oauth2/v2.0"
$Scope = "$DataverseUrl/.default offline_access openid"

