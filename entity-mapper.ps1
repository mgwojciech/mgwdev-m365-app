<#
.SYNOPSIS
    Generates TypeScript models for Dataverse tables.

.DESCRIPTION
    Reads VITE_FRONTEND_DATAVERSE_ENV from .env, signs in to Entra ID
    (as the Microsoft Power Platform CLI public client by default), lets you pick tables and writes
    one TypeScript file per table containing:
      - a metadata constant (logical name, entity set name, primary id/name attributes),
      - option set constants + union types for choice/state/status columns,
      - the model type with columns shaped as returned by the Dataverse Web API
        (lookups as _<name>_value) and navigation properties for relationships.

    The app's own client (VITE_FRONTEND_CLIENT_ID) is a SPA registration and cannot redeem tokens outside
    a browser, so a public client is used instead. Pass -ClientId to use another one; it needs
    http://localhost as a "Mobile and desktop applications" redirect URI (Interactive) or
    "Allow public client flows" enabled (DeviceCode).

.EXAMPLE
    .\entity-mapper.ps1
.EXAMPLE
    .\entity-mapper.ps1 -Tables test,contact -OutputPath src/model -Force
    
.EXAMPLE
    .\entity-mapper.ps1 -IncludeAllRelationships
#>
[CmdletBinding()]
param(
    [ValidateSet('Interactive', 'DeviceCode')]
    [string]$AuthFlow = 'Interactive',
    # Public client used to sign in; defaults to Microsoft Power Platform CLI (pac).
    [string]$ClientId = '9cee029c-6210-4654-90bb-17e6e9d36617',
    # Logical names of tables to map; skips the selection prompt.
    [string[]]$Tables,
    # Output folder (relative to this script or absolute); skips the location prompt.
    [string]$OutputPath,
    # Defaults to .env next to this script.
    [string]$EnvFile,
    # Emit navigation properties to tables that have no generated model (typed as Record<string, unknown>).
    [switch]$IncludeAllRelationships,
    # Use console prompts instead of Out-GridView for table selection.
    [switch]$NoGui,
    # Overwrite existing files without asking.
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

