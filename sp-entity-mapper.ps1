#region TypeScript generation

function ConvertTo-PascalCase([string]$Text) {
    $words = $Text -split '[^A-Za-z0-9]+' | Where-Object { $_ }
    return ($words | ForEach-Object { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) }) -join ''
}

function ConvertTo-Identifier([string]$Text, [string]$Fallback) {
    $name = ConvertTo-PascalCase $Text
    if (-not $name) { return $Fallback }
    if ($name -match '^\d') { return "_$name" }
    return $name
}

function Format-Comment([string]$Text) {
    return $Text.Replace('*/', '* /') -replace '\s+', ' '
}

function Format-StringLiteral([string]$Text) {
    return '"' + $Text.Replace('\', '\\').Replace('"', '\"') + '"'
}

# Decodes SharePoint internal name escapes such as _x0020_ (space).
function ConvertFrom-InternalName([string]$Name) {
    return [regex]::Replace($Name, '_x([0-9A-Fa-f]{4})_', { param($m) [string][char][Convert]::ToInt32($m.Groups[1].Value, 16) })
}

# Builds list id -> TypeScript type name, using the list title and falling back to the url name on clashes.
function Get-TypeNameMap($SiteLists) {
    $candidates = @{}
    foreach ($list in $SiteLists) {
        $candidates[$list.Id] = ConvertTo-Identifier $list.Title (ConvertTo-Identifier $list.Name 'List')
    }
    $clashes = $candidates.Values | Group-Object | Where-Object Count -gt 1 | ForEach-Object Name
    $map = @{}
    foreach ($list in $SiteLists) {
        $name = $candidates[$list.Id]
        if ($clashes -contains $name) { $name = ConvertTo-Identifier $list.Name $name }
        $map[$list.Id] = $name
    }
    return $map
}

# System fields that are hidden or read-only but returned by the REST API and worth typing.
$SystemFields = @('ID', 'Created', 'Modified', 'Author', 'Editor', 'GUID', 'FileLeafRef', 'FileRef', 'FileDirRef')

function Test-MappedField($Field) {
    if ($Field.TypeAsString -eq 'Computed' -or $Field.IsDependentLookup) { return $false }
    return -not $Field.Hidden -or $SystemFields -contains $Field.InternalName
}

$UserType = '{ Id?: number; Title?: string; EMail?: string; Name?: string }'

function New-ListModel($List, [string]$TypeName, $Fields, [scriptblock]$ResolveTargetType, [hashtable]$ListTitles) {
    $optionBlocks = New-Object System.Collections.Generic.List[string]
    $properties = New-Object System.Collections.Generic.List[string]
    $expandLines = New-Object System.Collections.Generic.List[string]
    $imports = New-Object System.Collections.Generic.SortedSet[string]
    $usedNames = @{ Id = $true }
    $skipped = 0

    $properties.Add('    /** Item id */')
    $properties.Add('    Id?: number | null;')

    foreach ($field in ($Fields | Where-Object { Test-MappedField $_ } | Sort-Object EntityPropertyName)) {
        $name = $field.EntityPropertyName
        if (-not $name -or $usedNames.ContainsKey($name)) { continue }
        $usedNames[$name] = $true

        $comment = $field.Title
        $tsType = $null

        switch ($field.TypeAsString) {
            { $_ -in 'Text', 'Note', 'Guid', 'DateTime', 'File', 'ContentTypeId', 'Thumbnail', 'Location' } { $tsType = 'string' }
            { $_ -in 'Counter', 'Integer', 'Number', 'Currency' } { $tsType = 'number' }
            { $_ -in 'Boolean', 'Attachments' } { $tsType = 'boolean' }
            'URL' { $tsType = '{ Description: string; Url: string }' }
            'Geolocation' { $tsType = '{ Latitude: number; Longitude: number; Altitude?: number; Measure?: number }' }
            'TaxonomyFieldType' { $tsType = '{ Label: string; TermGuid: string; WssId: number }' }
            'TaxonomyFieldTypeMulti' { $tsType = '{ Label: string; TermGuid: string; WssId: number }[]' }
            'Calculated' {
                switch ($field.OutputType) {
                    { $_ -in 9, 10, 'Number', 'Currency' } { $tsType = 'number' }
                    { $_ -in 8, 'Boolean' } { $tsType = 'boolean' }
                    default { $tsType = 'string' }
                }
            }
            { $_ -in 'Choice', 'MultiChoice' } {
                $isMulti = $_ -eq 'MultiChoice'
                $choices = @($field.Choices)
                if ($choices.Count -eq 0) {
                    $tsType = 'string'
                    if ($isMulti) { $tsType = 'string[]' }
                    break
                }
                $optionType = $TypeName + (ConvertTo-PascalCase (ConvertFrom-InternalName $field.InternalName))
                $usedKeys = @{}
                $index = 0
                $members = foreach ($choice in $choices) {
                    $index++
                    $key = ConvertTo-Identifier $choice "Choice$index"
                    if ($usedKeys.ContainsKey($key)) { $key = "${key}_$index" }
                    $usedKeys[$key] = $true
                    "    $key`: $(Format-StringLiteral $choice),"
                }
                $optionBlocks.Add((@(
                            "export const $optionType = {"
                            $members
                            '} as const;'
                            ''
                            "export type $optionType = (typeof $optionType)[keyof typeof $optionType];"
                        ) -join "`n"))
                $tsType = $optionType
                # Fill-in choices accept any text; (string & {}) keeps autocompletion of the known values.
                if ($field.FillInChoice) { $tsType = "$optionType | (string & {})" }
                if ($isMulti -and $field.FillInChoice) { $tsType = "($tsType)[]" }
                elseif ($isMulti) { $tsType = "$tsType[]" }
            }
            { $_ -in 'User', 'UserMulti' } {
                $isMulti = $_ -eq 'UserMulti' -or $field.AllowMultipleValues
                $suffix = ''
                if ($isMulti) { $suffix = '[]' }
                if ($comment) { $properties.Add("    /** $(Format-Comment $comment) (user id) */") }
                $properties.Add("    ${name}Id?: number$suffix | null;")
                $properties.Add("    ${name}StringId?: string$suffix | null;")
                $expandLines.Add("    /** $(Format-Comment "$comment (`$expand=$name)") */")
                if ($isMulti) { $expandLines.Add("    $name`?: $UserType[];") }
                else { $expandLines.Add("    $name`?: $UserType | null;") }
                break
            }
            { $_ -in 'Lookup', 'LookupMulti' } {
                $isMulti = $_ -eq 'LookupMulti' -or $field.AllowMultipleValues
                $suffix = ''
                if ($isMulti) { $suffix = '[]' }
                $targetId = $null
                if ($field.LookupList -and $field.LookupList -match '[0-9A-Fa-f-]{36}') { $targetId = ConvertTo-ListKey $Matches[0] }
                $targetTitle = $field.LookupList
                if ($targetId -and $ListTitles.ContainsKey($targetId)) { $targetTitle = $ListTitles[$targetId] }
                $properties.Add("    /** $(Format-Comment "$comment -> $targetTitle.$($field.LookupField)") */")
                $properties.Add("    ${name}Id?: number$suffix | null;")

                $targetType = $null
                if ($targetId) { $targetType = & $ResolveTargetType $targetId }
                if (-not $targetType) {
                    if (-not $IncludeAllRelationships) { $skipped++; break }
                    $targetType = 'Record<string, unknown>'
                }
                elseif ($targetType -ne $TypeName) {
                    [void]$imports.Add($targetType)
                }
                $expandLines.Add("    /** $(Format-Comment "$comment (`$expand=$name)") */")
                if ($isMulti) { $expandLines.Add("    $name`?: $targetType[];") }
                else { $expandLines.Add("    $name`?: $targetType | null;") }
                break
            }
        }

        if (-not $tsType) { continue }
        if ($comment) { $properties.Add("    /** $(Format-Comment $comment) */") }
        $properties.Add("    $name`?: $tsType | null;")
    }

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("// $GeneratedMarker from $SiteUrl - do not edit manually.")
    $lines.Add("// @list $($List.Id)")
    $lines.Add('')
    if ($imports.Count -gt 0) {
        foreach ($import in $imports) { $lines.Add("import type { $import } from `"./$import`";") }
        $lines.Add('')
    }
    $lines.Add("export const ${TypeName}Metadata = {")
    $lines.Add("    id: `"$($List.Id)`",")
    $lines.Add("    title: $(Format-StringLiteral $List.Title),")
    $lines.Add("    url: $(Format-StringLiteral $List.Url),")
    $lines.Add("    listItemEntityTypeFullName: `"$($List.ListItemEntityTypeFullName)`",")
    $lines.Add("    baseTemplate: $($List.BaseTemplate),")
    $lines.Add('} as const;')
    $lines.Add('')
    foreach ($block in $optionBlocks) {
        $lines.Add($block)
        $lines.Add('')
    }
    $lines.Add("/** $(Format-Comment $List.Title) ($($List.Url)) */")
    $lines.Add("export type $TypeName = {")
    $lines.AddRange($properties)
    if ($expandLines.Count -gt 0) {
        $lines.Add('')
        $lines.Add('    // Expanded lookup and person properties')
        $lines.AddRange($expandLines)
    }
    $lines.Add('};')

    return @{ Content = ($lines -join "`n") + "`n"; SkippedNavigation = $skipped }
}

