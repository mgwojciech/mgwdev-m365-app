function ConvertFrom-SelectionInput([string]$Text, [int]$Max) {
    $indexes = New-Object System.Collections.Generic.List[int]
    foreach ($part in ($Text -split '[,;\s]+' | Where-Object { $_ })) {
        if ($part -match '^(\d+)-(\d+)$') {
            [int]$Matches[1]..[int]$Matches[2] | ForEach-Object { $indexes.Add($_) }
        }
        elseif ($part -match '^\d+$') {
            $indexes.Add([int]$part)
        }
        else {
            Write-Warning "Ignoring '$part'."
        }
    }
    return $indexes | Where-Object { $_ -ge 1 -and $_ -le $Max } | Select-Object -Unique
}

function Select-ListsConsole($SiteLists) {
    while ($true) {
        $filter = Read-Host 'Filter lists by name (empty = all)'
        $candidates = @(switch ($filter) {
                '' { $SiteLists }
                default { $SiteLists | Where-Object { $_.Title -like "*$filter*" -or $_.Name -like "*$filter*" } }
            })
        if ($candidates.Count -eq 0) {
            Write-Host 'No lists match.' -ForegroundColor Yellow
            continue
        }
        for ($i = 0; $i -lt $candidates.Count; $i++) {
            Write-Host ('{0,4}. {1,-40} {2}' -f ($i + 1), $candidates[$i].Title, $candidates[$i].Url)
        }
        $answer = Read-Host 'Select lists (e.g. 1,3,5-7; empty = filter again)'
        $picked = @(ConvertFrom-SelectionInput $answer $candidates.Count | ForEach-Object { $candidates[$_ - 1] })
        if ($picked.Count -gt 0) { return $picked }
    }
}

function Select-Lists($SiteLists) {
    if (-not $NoGui -and (Get-Command Out-GridView -ErrorAction SilentlyContinue)) {
        Write-Host 'Select lists in the grid window (Ctrl/Shift for multi-select), then click OK.' -ForegroundColor Cyan
        $picked = @($SiteLists |
                Select-Object Title, Url, BaseTemplate, ItemCount, Id |
                Out-GridView -Title 'Select SharePoint lists to map' -OutputMode Multiple)
        return @($picked | ForEach-Object { $id = $_.Id; $SiteLists | Where-Object Id -eq $id })
    }
    return Select-ListsConsole $SiteLists
}

function Resolve-OutputPath([string]$Path) {
    if (-not $Path) { $Path = 'src/model' }
    if ($Path -match '^[A-Za-z]:[\\/]' -or $Path -match '^\\\\') { return $Path }
    return Join-Path $ScriptRoot ($Path.TrimStart('/', '\'))
}

