#region SharePoint metadata

function Invoke-SharePoint([string]$RelativeUrl) {
    $headers = @{
        Authorization = "Bearer $script:AccessToken"
        Accept        = 'application/json;odata=nometadata'
    }
    try {
        return Invoke-RestMethod -Method Get -Uri "$SiteUrl/_api/$RelativeUrl" -Headers $headers
    }
    catch {
        $raw = Get-ErrorBody $_
        if ($raw) { throw "SharePoint request failed ($RelativeUrl): $raw" }
        throw
    }
}

function ConvertTo-ListKey([string]$Id) {
    return $Id.Trim('{', '}').ToLowerInvariant()
}

# Returns all lists of the site, hidden ones included so lookups to them can be described.
function Get-SiteLists {
    $select = 'Id,Title,Hidden,IsCatalog,BaseTemplate,ItemCount,ListItemEntityTypeFullName,RootFolder/Name,RootFolder/ServerRelativeUrl'
    $result = Invoke-SharePoint "web/lists?`$select=$select&`$expand=RootFolder"
    return $result.value |
        ForEach-Object {
            [pscustomobject]@{
                Id                         = ConvertTo-ListKey $_.Id
                Title                      = $_.Title
                Name                       = $_.RootFolder.Name
                Url                        = $_.RootFolder.ServerRelativeUrl
                BaseTemplate               = [int]$_.BaseTemplate
                ItemCount                  = [int]$_.ItemCount
                Hidden                     = [bool]$_.Hidden -or [bool]$_.IsCatalog
                ListItemEntityTypeFullName = $_.ListItemEntityTypeFullName
            }
        } |
        Sort-Object Title
}

function Get-ListFields([string]$ListId) {
    return (Invoke-SharePoint "web/lists(guid'$ListId')/fields").value
}

