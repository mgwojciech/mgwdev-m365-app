<#
.SYNOPSIS
    Generates TypeScript models for SharePoint lists.

.DESCRIPTION
    Reads VITE_FRONTEND_SP_SITE_URL from .env (falling back to .env.development), signs in to Entra ID
    (as the Microsoft Azure CLI public client by default), lets you pick lists and writes
    one TypeScript file per list containing:
      - a metadata constant (list id, title, url, list item entity type),
      - choice constants + union types for Choice/MultiChoice columns,
      - the model type with columns shaped as returned by the SharePoint REST API with odata=nometadata
        (lookups and people as <Name>Id) and expanded properties for lookup and person columns.

    The app's own client (VITE_FRONTEND_CLIENT_ID) is a SPA registration and cannot redeem tokens outside
    a browser. Pass -ClientId (can be Your PnP.PowerShell app reg); it needs
    http://localhost as a "Mobile and desktop applications" redirect URI (Interactive) or
    "Allow public client flows" enabled (DeviceCode), plus delegated SharePoint permissions.

.EXAMPLE
    .\sp-entity-mapper.ps1
.EXAMPLE
    .\sp-entity-mapper.ps1 -SiteUrl https://contoso.sharepoint.com/sites/hr -Lists Employees,Departments -OutputPath src/model -Force
.EXAMPLE
    .\sp-entity-mapper.ps1 -IncludeAllRelationships
#>
[CmdletBinding()]
param(
    [ValidateSet('Interactive', 'DeviceCode')]
    [string]$AuthFlow = 'Interactive',
    # Public client used to sign in; defaults to Microsoft Azure CLI.
    [string]$ClientId,
    # Site to read lists from; defaults to VITE_FRONTEND_SP_SITE_URL.
    [string]$SiteUrl,
    # Titles, ids or url names of lists to map; skips the selection prompt.
    [string[]]$Lists,
    # Output folder (relative to this script or absolute); skips the location prompt.
    [string]$OutputPath,
    # Defaults to .env next to this script, with .env.development as fallback.
    [string]$EnvFile,
    # Emit expanded lookup properties to lists that have no generated model (typed as Record<string, unknown>).
    [switch]$IncludeAllRelationships,
    # Use console prompts instead of Out-GridView for list selection.
    [switch]$NoGui,
    # Overwrite existing files without asking.
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

# $PSScriptRoot is empty in some hosts (e.g. VS Code run/debug, dot-sourcing), so fall back to the script path or current folder.
$ScriptRoot = $PSScriptRoot
if (-not $ScriptRoot -and $MyInvocation.MyCommand.Path) { $ScriptRoot = Split-Path -Parent $MyInvocation.MyCommand.Path }
if (-not $ScriptRoot) { $ScriptRoot = (Get-Location).Path }
$EnvFiles = @($EnvFile)
if (-not $EnvFile) { $EnvFiles = @((Join-Path $ScriptRoot '.env'), (Join-Path $ScriptRoot '.env.development')) }
[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12

$GeneratedMarker = 'Generated by sp-entity-mapper.ps1'

#region Configuration

function Read-EnvFile([string]$Path) {
    $values = @{}
    if (-not (Test-Path $Path)) { return $values }
    foreach ($line in Get-Content $Path) {
        if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$' -and $line -notmatch '^\s*#') {
            $values[$Matches[1]] = $Matches[2].Trim('"', "'")
        }
    }
    return $values
}

function Get-Setting([hashtable[]]$EnvValues, [string]$Name) {
    $value = [Environment]::GetEnvironmentVariable($Name)
    foreach ($values in $EnvValues) {
        if (-not $value) { $value = $values[$Name] }
    }
    if (-not $value) { throw "Missing setting $Name (set it in $($EnvFiles -join ' or ') or as an environment variable)." }
    return $value
}

$envValues = @($EnvFiles | ForEach-Object { Read-EnvFile $_ })
$TenantId = Get-Setting $envValues 'VITE_FRONTEND_TENANT_ID'
if (-not $SiteUrl) { $SiteUrl = Get-Setting $envValues 'VITE_FRONTEND_SP_SITE_URL' }
$SiteUrl = $SiteUrl.TrimEnd('/')
$SharePointRoot = ([Uri]$SiteUrl).GetLeftPart([UriPartial]::Authority)

$Authority = "https://login.microsoftonline.com/$TenantId/oauth2/v2.0"
$Scope = "$SharePointRoot/.default offline_access openid"

