#region Main

Write-Host "SharePoint: $SiteUrl" -ForegroundColor Cyan
if ($AuthFlow -eq 'DeviceCode') { $script:AccessToken = Get-TokenDeviceCode }
else { $script:AccessToken = Get-TokenInteractive }
Write-Host 'Authenticated.' -ForegroundColor Green

Write-Host 'Loading lists...' -ForegroundColor Cyan
$allLists = @(Get-SiteLists)
$visibleLists = @($allLists | Where-Object { -not $_.Hidden })
$typeNames = Get-TypeNameMap $allLists
$listTitles = @{}
foreach ($list in $allLists) { $listTitles[$list.Id] = $list.Title }

if ($Lists) {
    $selected = @(foreach ($listName in $Lists) {
            $key = $listName.Trim('{', '}').ToLowerInvariant()
            $match = $allLists | Where-Object { $_.Id -eq $key -or $_.Title -eq $listName -or $_.Name -eq $listName } | Select-Object -First 1
            if (-not $match) { throw "List '$listName' not found." }
            $match
        })
}
else {
    $selected = @(Select-Lists $visibleLists)
}
if ($selected.Count -eq 0) {
    Write-Host 'No lists selected.' -ForegroundColor Yellow
    return
}
Write-Host "Selected: $(($selected | ForEach-Object Title) -join ', ')"

if (-not $OutputPath) {
    $OutputPath = Read-Host 'Model location [src/model]'
}
$outputDir = Resolve-OutputPath $OutputPath
if (-not (Test-Path $outputDir)) { New-Item -ItemType Directory -Path $outputDir | Out-Null }
Write-Host "Output: $outputDir"

$selectedIds = @($selected | ForEach-Object Id)
# A lookup target gets a typed expanded property when it is generated now or was generated earlier into the same folder.
$resolveTargetType = {
    param([string]$ListId)
    $name = $typeNames[$ListId]
    if (-not $name) { return $null }
    if ($selectedIds -contains $ListId) { return $name }
    $file = Join-Path $outputDir "$name.ts"
    if ((Test-Path $file) -and (Select-String -Path $file -SimpleMatch "// @list $ListId" -Quiet)) { return $name }
    return $null
}.GetNewClosure()

$utf8NoBom = New-Object Text.UTF8Encoding $false
$overwriteAll = [bool]$Force
foreach ($list in $selected) {
    $typeName = $typeNames[$list.Id]
    $file = Join-Path $outputDir "$typeName.ts"
    Write-Host "Mapping $($list.Title) -> $typeName.ts" -ForegroundColor Cyan

    if ((Test-Path $file) -and -not $overwriteAll) {
        $answer = Read-Host "  $typeName.ts exists. Overwrite? [y]es / [n]o / [a]ll"
        if ($answer -match '^a') { $overwriteAll = $true }
        elseif ($answer -notmatch '^y') { Write-Host '  Skipped.'; continue }
    }

    $fields = Get-ListFields $list.Id
    $model = New-ListModel $list $typeName $fields $resolveTargetType $listTitles
    [IO.File]::WriteAllText($file, $model.Content, $utf8NoBom)

    if ($model.SkippedNavigation -gt 0) {
        Write-Host "  Skipped $($model.SkippedNavigation) expanded lookups to unmapped lists (use -IncludeAllRelationships to keep them)." -ForegroundColor DarkGray
    }
}

Write-Host 'Done.' -ForegroundColor Green

